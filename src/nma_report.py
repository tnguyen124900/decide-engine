def build_report(inp: ReportInput) -> ReportBundle:
    L = _labels(inp.labels)
    tables = report_tables(inp)
    fit = _fit_for(inp)
    order = sup.ranking_order(fit)
    spec = inp.document.get("spec", {})
    pct = f"{float(spec.get('ci_level', 0.95)):.0%}"
    figures = {
        "network": network_png(inp.model, inp.summary),
        "forest": forest_png(fit, inp.result.measure, inp.result.reference, order,
                             f"{pct} {L['cri'] if inp.bayes is not None else L['ci']}"),
    }
    points = sup.transitivity_points(inp.summary, inp.document.get("study_characteristics", []) or [],
                                     sup.characteristic_variables(inp.document))
    if not points.empty:
        order = [f"{a} vs {b}" for (a, b) in inp.summary.edges]
        figures["transitivity"] = transitivity_png(points, order)
    if getattr(inp.bayes, "chain_draws", None) is not None:
        figures["trace"] = trace_png(inp.bayes.chain_draws, inp.bayes.parameter_names, getattr(inp.bayes, "chain_tau", None))
    methods = methods_paragraphs(inp)
    title = inp.title or inp.document.get("name") or L["report_title"]
    stem = sup.slug(title) or "nma-report"
    if inp.document.get("title"):
        stem += "-" + sup.slug(str(inp.document["title"]))
    return ReportBundle(
        docx_bytes=write_docx(inp, tables, figures, methods),
        xlsx_bytes=write_xlsx(tables, title, methods, SHEET_ORDER),
        figures=figures, filename_stem=stem,
    )
