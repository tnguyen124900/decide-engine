def methods_paragraphs(inp: ReportInput) -> list[str]:
    L = _labels(inp.labels)
    spec = inp.document.get("spec", {})
    pct = f"{float(spec.get('ci_level', 0.95)):.0%}"
    measure = inp.result.measure
    paragraphs = []
    if inp.bayes is None:
        paragraphs.append(L["methods_freq"].format(
            effects=inp.effects_label or inp.effects, measure=measure, pct=pct,
            df=inp.result.heterogeneity.prediction_df or "–"))
    else:
        bayes = spec.get("bayes", {})
        settings = getattr(inp.bayes, "settings", None)
        if settings and settings.tau_prior == "lognormal":
            family = "log-normal" if settings.tau_df is None else f"log-t ({settings.tau_df:g} df)"
            tau_prior = (f"{family}(μ = {settings.tau_mu:.2f}, σ = {settings.tau_sigma:.2f}) for τ² "
                         f"(informative; {settings.tau_prior_label or 'empirical predictive distribution'})")
        else:
            tau_prior = (f"Uniform(0, {settings.tau_max:g})" if settings and settings.tau_prior == "uniform"
                         else f"Half-normal(0, {settings.tau_scale:g})" if settings else "vague")
        common = dict(effects=inp.effects_label or inp.effects, pct=pct, prior_sd=f"{(settings.prior_sd if settings else 100):g}",
                      tau_prior=tau_prior, chains=settings.chains if settings else bayes.get("chains", 4),
                      draws=settings.draws_per_chain if settings else bayes.get("draws", 1000),
                      warmup=getattr(inp.bayes, "warmup", bayes.get("warmup", 1000)),
                      likelihood=LIKELIHOOD_LABELS.get(getattr(inp.bayes, "likelihood", ""), getattr(inp.bayes, "likelihood", "")) or "normal")
        key = "methods_bayes_exact" if getattr(inp.bayes, "likelihood", "") else "methods_bayes_normal"
        paragraphs.append(L[key].format(**common))
    class_model = getattr(inp.bayes, "class_model", "none")
    if inp.bayes is not None and class_model != "none":
        settings = inp.bayes.settings
        paragraphs.append(L[f"methods_class_{class_model}"].format(
            classes="; ".join(f"{c}: {', '.join(m)}" for c, m in inp.bayes.class_members.items()),
            prior_sd=f"{settings.prior_sd:g}", class_scale=f"{settings.class_sd_scale:g}"))
    if inp.inconsistency is not None:
        method = getattr(inp.inconsistency, "method", "side")
        paragraphs.append(L["methods_inconsistency"].format(
            split_method="SIDE, Dias 2010 / NICE TSD 4" if method == "side" else "SIDDE, Efthimiou 2019"))
    if inp.cinema is not None:
        paragraphs.append(L["methods_cinema"])
    if getattr(inp, "threshold", None) is not None and not inp.threshold.errors and inp.threshold.rows:
        paragraphs.append(L["methods_threshold"].format(basis=L[f"basis_{inp.threshold.basis}"]))
    if getattr(inp, "piecewise", None) is not None and not inp.piecewise.errors and inp.piecewise.estimates:
        paragraphs.append(L["methods_piecewise"])
    if getattr(inp, "survival", None) and inp.survival.get("fits"):
        paragraphs.append(L["methods_survival"])
    if getattr(inp, "dose", None) and inp.dose.get("fits"):
        paragraphs.append(L["methods_dose"])
    for key in ("maic", "mlnmr"):
        if (getattr(inp, "popadj", None) or {}).get(key):
            paragraphs.append(L[f"methods_{key}"])
    if getattr(inp, "design", None) is not None and not inp.design.errors and inp.design.scenarios:
        paragraphs.append(L["methods_design"])
    if getattr(inp, "components", None) is not None and not inp.components.errors and inp.components.fit is not None:
        paragraphs.append(L["methods_components"])
    paragraphs.append(L["methods_software"])
    return paragraphs


