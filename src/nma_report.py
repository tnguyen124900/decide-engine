def write_docx(inp: ReportInput, tables: dict[str, pd.DataFrame], figures: dict[str, bytes],
               methods: list[str]) -> bytes:
    L = _labels(inp.labels)
    spec = inp.document.get("spec", {})
    measure = inp.result.measure
    pct = f"{float(spec.get('ci_level', 0.95)):.0%}"
    reference = inp.result.reference
    doc = _Docx()
    title = inp.title or inp.document.get("name") or L["report_title"]
    doc.body.append(f'<w:p><w:pPr><w:pStyle w:val="Title"/></w:pPr>{_Docx._run(title)}</w:p>')
    subtitle = sup.analysis_title(inp.document, 0) if inp.document.get("title") else ""
    if subtitle:
        doc.paragraph(subtitle, size=12)
    if inp.author:
        doc.paragraph(inp.author)
    doc.paragraph(L["generated"].format(date=datetime.date.today().isoformat()), italic=True, size=9)

    doc.heading(L["sec_methods"])
    for text in methods:
        doc.paragraph(text)

    doc.heading(L["sec_network"])
    if "network" in figures:
        doc.image(figures["network"], 12.0)
        doc.caption(L["fig_network"])
    doc.table(tables["edges"])
    doc.caption(L["tab_edges"])
    if not tables["characteristics"].empty:
        doc.heading(L["sec_characteristics"])
        doc.table(tables["characteristics"])
        doc.caption(L["tab_characteristics"])
        if figures.get("transitivity"):
            doc.image(figures["transitivity"], 16.0)
            doc.caption(L["fig_transitivity"])

    doc.heading(L["sec_results"])
    if "forest" in figures:
        doc.image(figures["forest"], 16.0)
        doc.caption(L["fig_forest"].format(ref=reference, measure=measure, pct=pct))
    doc.table(tables["effects"])
    doc.caption(L["tab_effects"].format(ref=reference))
    if "sof" in tables:
        doc.heading(L["sec_sof"], 2)
        n_cols = len(tables["sof"].columns)
        widths = [16, 7, 9, 14, 10, 12, 11, 13, 10, 14, 9] if n_cols == 11 else [18, 8, 10, 16, 12, 18, 10]
        doc.table(tables["sof"], font_size=7, widths=widths[:n_cols])
        doc.caption(L["tab_sof"])
        for note in inp.sof_notes or []:
            doc.paragraph(note, size=8, italic=True)
    doc.heading(L["sec_league"], 2)
    doc.table(tables["league"], font_size=7)
    doc.caption(L["tab_league"].format(measure=measure))
    doc.heading(L["sec_ranking"], 2)
    doc.table(tables["ranking"])
    doc.caption(L["tab_ranking"])
    doc.heading(L["sec_heterogeneity"], 2)
    het = inp.result.heterogeneity
    doc.paragraph(L["het_text"].format(tau2=_fmt(het.tau2, 4), q=_fmt(het.q), df=het.df, p=_fmt_p(het.p_value),
                                       i2="–" if het.i2 is None else f"{het.i2 * 100:.0f}%"))

    doc.heading(L["sec_inconsistency"])
    if "design_by_treatment" in tables:
        dbt = inp.inconsistency.design_by_treatment
        p = dbt.p_between_random if dbt.p_between_random is not None else dbt.p_between
        q = dbt.q_between_random if dbt.q_between_random is not None else dbt.q_between
        doc.paragraph(L["dbt_text"].format(q=_fmt(q), df=dbt.df_between, p=_fmt_p(p)))
        doc.table(tables["design_by_treatment"])
    if "nodesplit" in tables and not tables["nodesplit"].empty:
        doc.table(tables["nodesplit"], font_size=7)
        doc.caption(L["tab_nodesplit"])
    if "bayes_nodesplit" in tables:
        doc.table(tables["bayes_nodesplit"])
        doc.caption(L["tab_nodesplit"] + " (Bayesian)")
    if inp.ume is not None and not inp.ume.errors and inp.bayes is not None:
        verdict = L["ume_bad"] if inp.bayes.dic - inp.ume.dic > 3 else L["ume_ok"]
        doc.paragraph(L["ume_text"].format(dic_c=_fmt(inp.bayes.dic, 1), dic_u=_fmt(inp.ume.dic, 1), verdict=verdict))
    if "design_by_treatment" not in tables and "nodesplit" not in tables:
        doc.paragraph(L["no_data"], italic=True)

    if "cinema" in tables:
        doc.heading(L["sec_cinema"])
        doc.table(tables["cinema"].drop(columns=["Note"]) if "Note" in tables["cinema"].columns else tables["cinema"], font_size=7)
        doc.caption(L["tab_cinema"])
        doc.table(tables["cinema_reasons"], font_size=7)
    if "contribution" in tables:
        doc.heading(L["sec_contribution"])
        doc.table(tables["contribution"], font_size=7)
        doc.caption(L["tab_contribution"])
    if "absolute" in tables:
        doc.heading(L["sec_absolute"])
        doc.table(tables["absolute"])
        doc.caption(L["tab_absolute"].format(p0=f"{(inp.baseline_risk or 0) * 100:.1f}%", ref=reference))
    if "dose_models" in tables:
        doc.heading(L["sec_dose"])
        doc.table(tables["dose_models"])
        doc.table(tables["dose_params"], font_size=8)
        doc.caption(L["tab_dose"].format(function=inp.dose.get("selected") or ""))
    if "maic_effects" in tables or "mlnmr_effects" in tables:
        doc.heading(L["sec_popadj"])
        if "maic_effects" in tables:
            doc.table(tables["maic_balance"], font_size=8)
            doc.table(tables["maic_effects"], font_size=8)
            doc.caption(L["tab_maic"])
        if "mlnmr_effects" in tables:
            doc.table(tables["mlnmr_coefficients"], font_size=7)
            doc.table(tables["mlnmr_effects"], font_size=8)
            doc.caption(L["tab_mlnmr"])
    if "survival_models" in tables:
        doc.heading(L["sec_survival"])
        doc.table(tables["survival_models"])
        doc.table(tables["survival_effects"], font_size=7)
        doc.caption(L["tab_survival"].format(model=inp.survival.get("selected") or "", ref=reference))
    if "piecewise" in tables:
        doc.heading(L["sec_piecewise"])
        doc.table(tables["piecewise"], font_size=7)
        doc.caption(L["tab_piecewise"].format(ref=inp.piecewise.reference, pct=pct))
        if "piecewise_ph" in tables:
            doc.table(tables["piecewise_ph"], font_size=7)
    if "design" in tables:
        doc.heading(L["sec_design"])
        doc.table(tables["design"], font_size=7)
        doc.caption(L["tab_design"].format(nrs=", ".join(inp.design.nrs), ref=reference, measure=measure, pct=pct))
    if "component_effects" in tables:
        cn = inp.components
        doc.heading(L["sec_components"])
        doc.table(tables["component_effects"])
        doc.table(tables["component_treatments"])
        doc.caption(L["tab_components"].format(
            measure=measure, ref=reference, q=f"{cn.q_diff:.2f}", df=cn.df_diff,
            p="–" if cn.p_additivity is None else f"{cn.p_additivity:.3f}"))
    if "threshold" in tables:
        doc.heading(L["sec_threshold"])
        doc.table(tables["threshold"], font_size=7)
        doc.caption(L["tab_threshold"].format(basis=L[f"basis_{inp.threshold.basis}"], best=inp.threshold.best))
    if "bayes_diagnostics" in tables:
        doc.heading(L["sec_fit"])
        doc.table(tables["model_fit"])
        doc.table(tables["bayes_diagnostics"], font_size=7)
        doc.caption(L["tab_fit"])
        if "class_effects" in tables:
            doc.table(tables["class_effects"])
            doc.caption(L["tab_class"].format(ref=reference, measure=measure, pct=pct))
        if figures.get("trace"):
            doc.image(figures["trace"], 16.0)
            doc.caption(L["fig_trace"])

    doc.heading(L["sec_prisma"])
    doc.table(tables["prisma"], font_size=7, widths=[5, 9, 16, 42, 11, 24])
    doc.caption(L["tab_prisma"])

    doc.heading(L["sec_references"])
    for i, ref in enumerate(REFERENCES, start=1):
        doc.paragraph(f"{i}. {ref}", size=9)
    return doc.to_bytes()


