@dataclass
class ReportInput:
    document: dict[str, Any]
    model: Any  # NetworkMetaAnalysis
    summary: Any  # NetworkSummary
    result: Any  # NMAResult (frequentist)
    effects: str = "random"
    labels: dict[str, str] = field(default_factory=dict)  # translated strings (see DEFAULT_LABELS)
    bayes: Any = None  # BayesResult / ExactResult or None
    inconsistency: Any = None  # InconsistencyResult or None
    cinema: Any = None  # CinemaResult or None
    contribution: Any = None  # ContributionResult or None
    absolute: list | None = None  # list[AbsoluteEffect]
    baseline_risk: float | None = None
    ume: Any = None  # ExactResult (UME) or None
    bayes_splits: list | None = None  # list[BayesNodeSplit]
    title: str = ""
    author: str = ""
    language: str = "en"
    effects_label: str = ""  # localised "random" / "fixed" for the methods text
    sof: Any = None  # pd.DataFrame from nma_sof.sof_frame, or None
    sof_notes: list[str] | None = None
    threshold: Any = None  # nma_threshold.ThresholdResult or None
    components: Any = None  # nma_components.ComponentResult or None
    design: Any = None  # nma_design.DesignResult or None
    piecewise: Any = None  # nma_timevarying.PiecewiseResult or None
    dose: Any = None  # {"fits": {function: MbnmaResult}, "selected": function} or None
    popadj: Any = None  # {"maic": {...frames}, "mlnmr": {...frames}} or None
    survival: Any = None  # {"fits": {label: SurvivalResult}, "selected": label} or None


@dataclass
class ReportBundle:
    docx_bytes: bytes
    xlsx_bytes: bytes
    figures: dict[str, bytes]  # name -> PNG
    filename_stem: str


