CHAIN_COLORS = ["1e3a8a", "dc2626", "059669", "d97706", "7c3aed", "0891b2", "be185d", "65a30d"]


def trace_png(chain_draws, names: list[str], chain_tau=None, width: int = 1600, max_points: int = 400) -> bytes:
    """Grid of trace plots (one panel per parameter, one line per chain) with a
    marginal density strip on the right of each panel."""

    from PIL import Image, ImageDraw
    import numpy as np

    series = [(name, chain_draws[:, :, i]) for i, name in enumerate(names)]
    if chain_tau is not None:
        series.append(("tau", chain_tau))
    if not series:
        return b""
    cols = 2 if len(series) > 1 else 1
    rows_n = (len(series) + cols - 1) // cols
    panel_w = width // cols
    panel_h = 260
    image = Image.new("RGB", (width, panel_h * rows_n + 40), "white")
    draw = ImageDraw.Draw(image)
    font, small = _font(22), _font(18)
    for index, (name, values) in enumerate(series):
        r, c = divmod(index, cols)
        x0, y0 = c * panel_w + 70, r * panel_h + 50
        trace_w = int(panel_w * 0.62)
        dens_w = int(panel_w * 0.2)
        h = panel_h - 90
        lo, hi = float(np.min(values)), float(np.max(values))
        if hi - lo < 1e-12:
            hi = lo + 1e-6
        pad = 0.05 * (hi - lo)
        lo, hi = lo - pad, hi + pad
        draw.rectangle([x0, y0, x0 + trace_w, y0 + h], outline="#cbd5e1")
        draw.text((x0, y0 - 32), name, fill="#0f172a", font=font)
        draw.text((x0 + trace_w + 6, y0 - 4), f"{hi:.3g}", fill="#475569", font=small)
        draw.text((x0 + trace_w + 6, y0 + h - 20), f"{lo:.3g}", fill="#475569", font=small)
        n_chain, n_draw = values.shape
        step = max(1, n_draw // max_points)
        for ch in range(n_chain):
            color = "#" + CHAIN_COLORS[ch % len(CHAIN_COLORS)]
            pts = [(x0 + trace_w * i / max(n_draw - 1, 1), y0 + h - h * (values[ch, i] - lo) / (hi - lo))
                   for i in range(0, n_draw, step)]
            if len(pts) > 1:
                draw.line(pts, fill=color, width=1)
        # density strip (histogram of all chains)
        hist, edges = np.histogram(values.reshape(-1), bins=40, range=(lo, hi))
        dx0 = x0 + trace_w + 70
        peak = max(int(hist.max()), 1)
        for count, e0, e1 in zip(hist, edges[:-1], edges[1:]):
            ya = y0 + h - h * (e1 - lo) / (hi - lo)
            yb = y0 + h - h * (e0 - lo) / (hi - lo)
            draw.rectangle([dx0, ya, dx0 + dens_w * count / peak, yb], fill="#93c5fd", outline="#93c5fd")
        draw.text((x0, y0 + h + 6), f"{n_chain} chains × {n_draw} draws", fill="#475569", font=small)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def _nice_step(span: float, target: int = 5) -> tuple[float, int]:
    """Tick step (1, 2 or 5 x 10^k) giving about `target` ticks over `span`, and
    the decimals needed to print it."""

    raw = span / target
    magnitude = 10 ** math.floor(math.log10(raw))
    step = next(m * magnitude for m in (1, 2, 5, 10) if m * magnitude >= raw)
    return step, max(0, -math.floor(math.log10(step) + 1e-9))


ROB_COLORS = {"Low": "#16a34a", "Some concerns": "#f59e0b", "High": "#dc2626", "Not recorded": "#94a3b8"}


def transitivity_png(points: pd.DataFrame, order: list[str] | None = None, width: int = 1600,
                     max_variables: int = 6) -> bytes:
    """Dot plots of the numeric study characteristics by direct comparison (one
    panel per variable, one row per comparison, one dot per study coloured by
    risk of bias, interquartile bar with the median). Empty bytes when there is
    nothing to draw."""

    from PIL import Image, ImageDraw
    import numpy as np

    if points is None or points.empty:
        return b""
    labels = list(dict.fromkeys(points["label"]))[:max_variables]
    comparisons = order or list(dict.fromkeys(points["comparison"]))
    comparisons = [c for c in comparisons if c in set(points["comparison"])]
    cols = 2 if len(labels) > 1 else 1
    panel_w = width // cols
    row_h, top, bottom = 40, 60, 60
    panel_h = top + row_h * len(comparisons) + bottom
    rows_n = (len(labels) + cols - 1) // cols
    legend_h = 50
    image = Image.new("RGB", (width, panel_h * rows_n + legend_h), "white")
    draw = ImageDraw.Draw(image)
    font, small = _font(22), _font(18)
    label_w = 250

    def shorten(text: str, limit: int) -> str:
        while len(text) > 3 and draw.textlength(text, font=small) > limit:
            text = text[:-2]
            if draw.textlength(text + "…", font=small) <= limit:
                return text + "…"
        return text

    for index, label in enumerate(labels):
        r, c = divmod(index, cols)
        x_label = c * panel_w + 20
        x0 = c * panel_w + label_w + 20
        x1 = (c + 1) * panel_w - 40
        y0 = r * panel_h + top
        frame = points[points["label"] == label]
        lo, hi = float(frame["value"].min()), float(frame["value"].max())
        if hi - lo < 1e-9:
            lo, hi = lo - 0.5, hi + 0.5
        pad = 0.06 * (hi - lo)
        lo, hi = lo - pad, hi + pad

        def xpos(value: float) -> float:
            return x0 + (x1 - x0) * (value - lo) / (hi - lo)

        draw.text((x_label, r * panel_h + 14), label, fill="#0f172a", font=font)
        y_axis = y0 + row_h * len(comparisons)
        draw.line([(x0, y_axis), (x1, y_axis)], fill="#94a3b8", width=1)
        step, decimals = _nice_step(hi - lo)
        tick = math.ceil(lo / step) * step
        while tick <= hi + 1e-9:
            text = f"{tick:.{decimals}f}"
            draw.line([(xpos(tick), y0), (xpos(tick), y_axis)], fill="#e2e8f0", width=1)
            draw.text((xpos(tick) - draw.textlength(text, font=small) / 2, y_axis + 6), text, fill="#475569", font=small)
            tick += step
        for k, comparison in enumerate(comparisons):
            yc = y0 + row_h * k + row_h / 2
            draw.text((x_label, yc - 10), shorten(comparison, label_w - 12), fill="#334155", font=small)
            sub = frame[frame["comparison"] == comparison]
            if sub.empty:
                continue
            values = sub["value"].to_numpy(dtype=float)
            q1, med, q3 = (float(v) for v in np.percentile(values, [25, 50, 75]))
            draw.rectangle([xpos(q1), yc - 9, max(xpos(q3), xpos(q1) + 2), yc + 9], fill="#dbeafe", outline="#93c5fd")
            draw.line([(xpos(med), yc - 12), (xpos(med), yc + 12)], fill="#1e3a8a", width=3)
            seen: dict[float, int] = {}
            for value, rob in zip(sub["value"], sub["rob"]):
                n_same = seen.get(round(float(value), 6), 0)
                seen[round(float(value), 6)] = n_same + 1
                dy = ((n_same + 1) // 2) * 8 * (1 if n_same % 2 else -1)
                cx, cy = xpos(float(value)), yc + dy
                draw.ellipse([cx - 6, cy - 6, cx + 6, cy + 6], fill=ROB_COLORS.get(rob, ROB_COLORS["Not recorded"]),
                             outline="white")
    x = 20
    y = panel_h * rows_n + 12
    for level, color in ROB_COLORS.items():
        draw.ellipse([x, y + 4, x + 14, y + 18], fill=color)
        draw.text((x + 22, y), level, fill="#334155", font=small)
        x += 40 + int(draw.textlength(level, font=small))
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def _fit_for(inp: ReportInput):
    if inp.bayes is not None and getattr(inp.bayes, "fit", None) is not None:
        return inp.bayes.fit
    return inp.result.random if inp.effects == "random" else inp.result.fixed


def report_tables(inp: ReportInput) -> dict[str, pd.DataFrame]:
    L = _labels(inp.labels)
    measure = inp.result.measure
    fit = _fit_for(inp)
    order = sup.ranking_order(fit)
    tables: dict[str, pd.DataFrame] = {}

    tables["edges"] = pd.DataFrame([{
        L["comparison"]: f"{a} vs {b}", L["studies"]: edge.n_studies, L["patients"]: int(edge.patients),
        "IDs": ", ".join(edge.study_ids),
    } for (a, b), edge in inp.summary.edges.items()])

    characteristics = inp.document.get("study_characteristics", [])
    tables["characteristics"] = sup.transitivity_frame(inp.summary, characteristics, sup.characteristic_variables(inp.document))

    bayes_on = inp.bayes is not None
    interval = L["cri"] if bayes_on else L["ci"]
    rows = []
    for effect in fit.effects:
        row = {L["treatment"]: effect.treatment, f"{measure}": _fmt(effect.natural),
               f"{interval}": f"{_fmt(effect.natural_lower)} to {_fmt(effect.natural_upper)}"}
        if effect.natural_pred_lower is not None:
            row[L["pi"]] = f"{_fmt(effect.natural_pred_lower)} to {_fmt(effect.natural_pred_upper)}"
        row[L["sucra"] if bayes_on else L["score"]] = _fmt(fit.p_scores.get(effect.treatment), 3)
        if bayes_on and getattr(inp.bayes, "mean_rank", None):
            row[L["rank"]] = _fmt(inp.bayes.mean_rank.get(effect.treatment), 2)
        rows.append(row)
    tables["effects"] = pd.DataFrame(rows)
    tables["league"] = sup.league_frame(fit, order).reset_index().rename(columns={"index": ""})
    tables["ranking"] = pd.DataFrame([{
        L["treatment"]: name, L["sucra"] if bayes_on else L["score"]: _fmt(fit.p_scores.get(name), 3),
        **({L["rank"]: _fmt(inp.bayes.mean_rank.get(name), 2)} if bayes_on and getattr(inp.bayes, "mean_rank", None) else {}),
    } for name in order])

    het = inp.result.heterogeneity
    tables["heterogeneity"] = pd.DataFrame([{
        "τ²": _fmt(het.tau2, 4), "τ": _fmt(het.tau, 4), "Q": _fmt(het.q, 2), "df": het.df, "p": _fmt_p(het.p_value),
        "I²": "–" if het.i2 is None else f"{het.i2 * 100:.1f}%",
    }])

    if inp.inconsistency is not None and not inp.inconsistency.errors:
        inc = inp.inconsistency
        splits = inc.splits_random if inp.effects == "random" and inc.splits_random else inc.splits_fixed
        frame = sup.node_split_frame(splits, measure)
        tables["nodesplit"] = frame.drop(columns=["_flag"]) if "_flag" in frame.columns else frame
        dbt = inc.design_by_treatment
        if dbt is not None:
            rows = [{"": "Total", "Q": _fmt(dbt.q_total), "df": dbt.df_total, "p": "–"},
                    {"": "Within designs", "Q": _fmt(dbt.q_within), "df": dbt.df_within, "p": _fmt_p(dbt.p_within)},
                    {"": "Between designs", "Q": _fmt(dbt.q_between), "df": dbt.df_between, "p": _fmt_p(dbt.p_between)}]
            if dbt.q_between_random is not None:
                rows.append({"": "Between designs (random)", "Q": _fmt(dbt.q_between_random), "df": dbt.df_between,
                             "p": _fmt_p(dbt.p_between_random)})
            tables["design_by_treatment"] = pd.DataFrame(rows)
    if inp.bayes_splits:
        tables["bayes_nodesplit"] = pd.DataFrame([{
            L["comparison"]: f"{s.treatment} vs {s.versus}", L["direct"]: sup.format_effect(s.direct.natural, s.direct.natural_lower, s.direct.natural_upper),
            L["indirect"]: sup.format_effect(s.indirect.natural, s.indirect.natural_lower, s.indirect.natural_upper),
            "p": _fmt_p(s.p_value), "DIC": _fmt(s.dic, 1),
        } for s in inp.bayes_splits])

    if inp.cinema is not None and not inp.cinema.errors:
        from heor_tree_engine.nma_cinema import DOMAIN_LABELS, DOMAINS, cinema_report_rows

        rows = cinema_report_rows(inp.cinema)
        tables["cinema"] = pd.DataFrame([{
            L["comparison"]: r["Comparison"], measure: f"{_fmt(r['Estimate'])} ({_fmt(r['Lower'])} to {_fmt(r['Upper'])})",
            "Direct %": r["Direct evidence %"], **{DOMAIN_LABELS[d]: r[DOMAIN_LABELS[d]] for d in DOMAINS},
            L["confidence"]: r["Confidence"], "Note": r.get("Note", ""),
        } for r in rows])
        tables["cinema_reasons"] = pd.DataFrame([{L["comparison"]: r["Comparison"], "Reasons": r["Reasons"]} for r in rows])
    if inp.contribution is not None and not inp.contribution.errors:
        tables["contribution"] = sup.contribution_frame(inp.contribution)
    if inp.absolute:
        per = 1000.0
        tables["absolute"] = pd.DataFrame([{
            L["comparison"]: f"{row.treatment} vs {row.versus}",
            "Reference /1000": f"{row.baseline_risk * per:.0f}",
            "Treatment /1000": f"{row.risk * per:.0f} ({row.risk_lower * per:.0f} to {row.risk_upper * per:.0f})",
            "Difference /1000": f"{row.difference * per:+.0f} ({row.difference_lower * per:+.0f} to {row.difference_upper * per:+.0f})",
            "NNT": row.nnt_text,
        } for row in inp.absolute])
    if inp.bayes is not None:
        b = inp.bayes
        rows = [{"Parameter": d.name, "Median": _fmt(d.median, 4), "SD": _fmt(d.sd, 4),
                 f"{L['cri']} lower": _fmt(d.lower, 4), f"{L['cri']} upper": _fmt(d.upper, 4),
                 "R-hat": _fmt(d.rhat, 3), "ESS": int(round(d.ess))} for d in b.diagnostics]
        tables["bayes_diagnostics"] = pd.DataFrame(rows)
        fit_rows = [{"Model": "Consistency", "Dres": _fmt(b.residual_deviance, 1), "Data points": b.n_data_points,
                     "pD": _fmt(b.p_d, 1), "DIC": _fmt(b.dic, 1)}]
        if inp.ume is not None and not inp.ume.errors:
            fit_rows.append({"Model": "UME", "Dres": _fmt(inp.ume.residual_deviance, 1), "Data points": inp.ume.n_data_points,
                             "pD": _fmt(inp.ume.p_d, 1), "DIC": _fmt(inp.ume.dic, 1)})
        tables["model_fit"] = pd.DataFrame(fit_rows)
        if getattr(b, "class_effects", None):
            tables["class_effects"] = sup.class_effects_frame(b, inp.result.measure, L["cri"])
    if getattr(inp, "threshold", None) is not None and not inp.threshold.errors and inp.threshold.rows:
        tables["threshold"] = sup.threshold_frame(inp.threshold)
    if getattr(inp, "design", None) is not None and not inp.design.errors and inp.design.scenarios:
        tables["design"] = sup.design_frame(inp.design)
    if getattr(inp, "piecewise", None) is not None and not inp.piecewise.errors and inp.piecewise.estimates:
        tables["piecewise"] = sup.piecewise_frame(inp.piecewise)
        if inp.piecewise.ph:
            tables["piecewise_ph"] = sup.ph_frame(inp.piecewise)
    ds = getattr(inp, "dose", None)
    if ds and ds.get("fits"):
        tables["dose_models"] = sup.mbnma_models_frame(ds["fits"])
        chosen = ds["fits"].get(ds.get("selected")) or next(iter(ds["fits"].values()))
        tables["dose_params"] = sup.mbnma_params_frame(chosen)
    pa = getattr(inp, "popadj", None) or {}
    if pa.get("maic"):
        tables["maic_balance"], tables["maic_effects"] = pa["maic"]["balance"], pa["maic"]["effects"]
    if pa.get("mlnmr"):
        tables["mlnmr_coefficients"], tables["mlnmr_effects"] = pa["mlnmr"]["coefficients"], pa["mlnmr"]["effects"]
    sv = getattr(inp, "survival", None)
    if sv and sv.get("fits"):
        tables["survival_models"] = sup.survival_models_frame(sv["fits"])
        chosen = sv["fits"].get(sv.get("selected")) or next(iter(sv["fits"].values()))
        tables["survival_effects"] = sup.survival_effects_frame(chosen)
    cn = getattr(inp, "components", None)
    if cn is not None and not cn.errors and cn.fit is not None:
        tables["component_effects"] = sup.component_effects_frame(cn, L["ci"])
        tables["component_treatments"] = sup.component_treatments_frame(cn)

    spec = inp.document.get("spec", {})
    tables["settings"] = pd.DataFrame([{"Setting": k, "Value": str(v)} for k, v in spec.items() if k != "bayes"]
                                      + [{"Setting": f"bayes.{k}", "Value": str(v)} for k, v in spec.get("bayes", {}).items()])
    tables["data_arms"] = sup.arms_frame(inp.document)
    tables["data_contrasts"] = sup.contrasts_frame(inp.document)
    tables["data_characteristics"] = sup.characteristics_frame(inp.document)
    tables["treatments"] = sup.treatments_frame(inp.document)
    if inp.sof is not None and not inp.sof.empty:
        tables["sof"] = inp.sof
    tables["prisma"] = nma_prisma.report_frame(nma_prisma.checklist_frame(inp.document, prisma_auto(inp)))
    return tables


def prisma_auto(inp: ReportInput) -> dict[str, tuple[str, str]]:
    characteristics = inp.document.get("study_characteristics") or []
    has_rob = any(str(row.get("rob", "") or "").strip() for row in characteristics)
    has_chars = any(any(str(v or "").strip() for k, v in row.items() if k not in ("study", "rob")) for row in characteristics)
    return nma_prisma.auto_status(
        has_characteristics=has_chars, has_rob=has_rob,
        has_inconsistency=inp.inconsistency is not None and not inp.inconsistency.errors,
        has_cinema=inp.cinema is not None, has_funnel=inp.cinema is not None and getattr(inp.cinema, "funnel", None) is not None,
        bayes=inp.bayes is not None, has_absolute=bool(inp.absolute),
        extra_analyses=[name for name, present in (("leave-one-out", True), ("prior sensitivity (τ)", inp.bayes is not None),
                                                   ("network meta-regression", True), ("UME model", inp.ume is not None)) if present])


