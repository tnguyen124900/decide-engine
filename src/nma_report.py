def _font(size: int):
    from PIL import ImageFont

    for path in ("/System/Library/Fonts/Supplemental/Arial.ttf", "/Library/Fonts/Arial.ttf",
                 "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "C:/Windows/Fonts/arial.ttf"):
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # older Pillow
        return ImageFont.load_default()


def _hex_rgb(color: str) -> tuple[int, int, int]:
    color = (color or "#1e3a8a").lstrip("#")
    return tuple(int(color[i:i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def network_png(model, summary, colors: dict[str, str] | None = None, size: int = 1400) -> bytes:
    """Circular layout; node area ~ patients, edge width ~ studies."""

    from PIL import Image, ImageDraw

    names = list(summary.treatments) or list(model.treatment_names)
    colors = colors or sup.node_colors(model, "class")
    image = Image.new("RGB", (size, size), "white")
    draw = ImageDraw.Draw(image)
    centre = size / 2
    radius = size * 0.36
    positions = {}
    for i, name in enumerate(names):
        angle = -math.pi / 2 + 2 * math.pi * i / max(1, len(names))
        positions[name] = (centre + radius * math.cos(angle), centre + radius * math.sin(angle))
    max_studies = max((edge.n_studies for edge in summary.edges.values()), default=1)
    for (a, b), edge in summary.edges.items():
        width = max(2, int(2 + 14 * edge.n_studies / max_studies))
        draw.line([positions[a], positions[b]], fill=(148, 163, 184), width=width)
    max_patients = max(summary.patients.values(), default=1.0) or 1.0
    font = _font(int(size * 0.026))
    small = _font(int(size * 0.02))
    for name in names:
        x, y = positions[name]
        r = size * (0.025 + 0.045 * math.sqrt(max(summary.patients.get(name, 0.0), 0.0) / max_patients))
        draw.ellipse([x - r, y - r, x + r, y + r], fill=_hex_rgb(colors.get(name, "#1e3a8a")), outline="white", width=4)
        label = name
        w = draw.textlength(label, font=font)
        draw.text((x - w / 2, y + r + 6), label, fill=(15, 23, 42), font=font)
        note = f"{int(summary.patients.get(name, 0))} · {summary.n_studies.get(name, 0)}"
        w2 = draw.textlength(note, font=small)
        draw.text((x - w2 / 2, y + r + 6 + font.size + 4), note, fill=(71, 85, 105), font=small)
    for (a, b), edge in summary.edges.items():
        (x1, y1), (x2, y2) = positions[a], positions[b]
        label = str(edge.n_studies)
        w = draw.textlength(label, font=small)
        mx, my = (x1 + x2) / 2, (y1 + y2) / 2
        draw.rectangle([mx - w / 2 - 6, my - small.size / 2 - 3, mx + w / 2 + 6, my + small.size / 2 + 3], fill="white",
                       outline=(203, 213, 225))
        draw.text((mx - w / 2, my - small.size / 2), label, fill=(30, 41, 59), font=small)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def forest_png(fit, measure: str, reference: str, order: list[str], interval_label: str, width: int = 1600) -> bytes:
    """Horizontal forest plot of each treatment vs the reference."""

    from PIL import Image, ImageDraw

    ratio = is_ratio_measure(measure)
    effects = {e.treatment: e for e in fit.effects}
    rows = [effects[name] for name in order if name in effects]
    if not rows:
        rows = list(fit.effects)
    row_h = 70
    top, bottom = 90, 80
    left, right = 320, 380
    height = top + bottom + row_h * len(rows)
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    font = _font(26)
    small = _font(22)
    transform = (lambda v: math.log(v)) if ratio else (lambda v: v)
    values = [transform(v) for e in rows for v in (e.natural_lower, e.natural_upper)
              if v is not None and v > 0] if ratio else [v for e in rows for v in (e.natural_lower, e.natural_upper)]
    if ratio:
        values.append(0.0)
    else:
        values.append(0.0)
    low, high = min(values), max(values)
    pad = (high - low) * 0.08 or 1.0
    low, high = low - pad, high + pad
    plot_left, plot_right = left, width - right

    def xpos(value: float) -> float:
        return plot_left + (value - low) / (high - low) * (plot_right - plot_left)

    null_x = xpos(0.0)
    draw.line([(null_x, top - 20), (null_x, height - bottom + 10)], fill=(51, 65, 85), width=2)
    # axis ticks
    ticks = [0.25, 0.5, 1, 2, 4, 8] if ratio else None
    if ratio:
        for t in ticks:
            v = math.log(t)
            if low <= v <= high:
                x = xpos(v)
                draw.line([(x, height - bottom + 10), (x, height - bottom + 20)], fill=(100, 116, 139), width=2)
                w = draw.textlength(str(t), font=small)
                draw.text((x - w / 2, height - bottom + 24), str(t), fill=(71, 85, 105), font=small)
    else:
        span = high - low
        step = 10 ** math.floor(math.log10(span / 4)) if span > 0 else 1
        for k in range(int(math.floor(low / step)), int(math.ceil(high / step)) + 1):
            v = k * step
            if low <= v <= high:
                x = xpos(v)
                draw.line([(x, height - bottom + 10), (x, height - bottom + 20)], fill=(100, 116, 139), width=2)
                text = f"{v:g}"
                w = draw.textlength(text, font=small)
                draw.text((x - w / 2, height - bottom + 24), text, fill=(71, 85, 105), font=small)
    title = f"{measure} vs {reference} ({interval_label})"
    draw.text((left, 26), title, fill=(15, 23, 42), font=font)
    for i, effect in enumerate(rows):
        y = top + row_h * i + row_h / 2
        draw.text((24, y - font.size / 2), effect.treatment, fill=(15, 23, 42), font=font)
        if effect.natural_pred_lower is not None and effect.natural_pred_upper is not None:
            pl, pu = transform(effect.natural_pred_lower), transform(effect.natural_pred_upper)
            draw.line([(xpos(pl), y), (xpos(pu), y)], fill=(191, 219, 254), width=14)
        lo, hi = transform(effect.natural_lower), transform(effect.natural_upper)
        draw.line([(xpos(lo), y), (xpos(hi), y)], fill=(30, 58, 138), width=5)
        for xv in (lo, hi):
            draw.line([(xpos(xv), y - 10), (xpos(xv), y + 10)], fill=(30, 58, 138), width=4)
        cx = xpos(transform(effect.natural))
        draw.rectangle([cx - 9, y - 9, cx + 9, y + 9], fill=(30, 58, 138))
        label = sup.format_effect(effect.natural, effect.natural_lower, effect.natural_upper)
        draw.text((plot_right + 24, y - font.size / 2), label, fill=(15, 23, 42), font=font)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


