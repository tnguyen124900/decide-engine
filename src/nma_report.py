def _fmt(value, digits: int = 2) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "–"
    return f"{value:.{digits}f}"


def _fmt_p(value) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "–"
    return "<0.001" if value < 0.001 else f"{value:.3f}"


