"""Report export for the NMA Editor: one Word (.docx) and one Excel (.xlsx)
file with everything a PRISMA-NMA style results section needs.

Streamlit-free so it can be unit-tested. The .docx is written directly as
Office Open XML (no python-docx dependency): headings, paragraphs, tables
with a dark-blue header row, and PNG figures. Figures (network diagram,
forest plot) are drawn with Pillow so no browser or vl-convert is needed.
Excel uses openpyxl through pandas.

Entry point: `build_report(ReportInput) -> ReportBundle` with `.docx_bytes`,
`.xlsx_bytes`, `.figures`.
"""

